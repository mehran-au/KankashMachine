function km_t(string $key): string
{
    global $KM_T;
    return $KM_T[$key] ?? $key;
}

function km_lang_toggle_url(): string
{
    global $KM_LANG;
    $target = $KM_LANG === 'fa' ? 'en' : 'fa';
    $path = km_request_path();
    $query = $_GET;
    unset($query['lang']);
    $query['lang'] = $target;
    $qs = http_build_query($query);
    return km_url($path) . '?' . $qs;
}
